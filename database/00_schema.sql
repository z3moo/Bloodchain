CREATE TABLE NHOM_MAU (
  MaNhomMau VARCHAR(5) PRIMARY KEY,
  TenNhomMau NVARCHAR(10)
);
GO

CREATE TABLE CHIEN_DICH (
  MaChienDich VARCHAR(20) PRIMARY KEY,
  TenChienDich NVARCHAR(150),
  DiaDiem NVARCHAR(200),
  ThoiGian DATETIME,
  SoLuongDuKien INT,
  SoLuongThucTe INT
);
GO

CREATE TABLE BENH_VIEN (
  MaBV VARCHAR(20) PRIMARY KEY,
  TenBV NVARCHAR(150) NOT NULL,
  DiaChi NVARCHAR(250),
  SDT VARCHAR(15)
);
GO

CREATE TABLE NHAN_VIEN (
  MaNV VARCHAR(20) PRIMARY KEY,
  HoTen NVARCHAR(120),
  ChucVu NVARCHAR(100),
  Email VARCHAR(120)
);
GO

CREATE TABLE NGUOI_HIEN (
  MaNguoiHien VARCHAR(20) PRIMARY KEY,
  HoTen NVARCHAR(120) NOT NULL,
  NgaySinh DATE,
  GioiTinh NVARCHAR(10),
  CCCD VARCHAR(20) UNIQUE,
  SDT VARCHAR(15),
  BenhLy NVARCHAR(500),
  DiemTichLuy INT DEFAULT 0,
  HangThanhVien NVARCHAR(20) DEFAULT 'Bronze',
  MaNhomMau VARCHAR(5),
  FOREIGN KEY (MaNhomMau) REFERENCES NHOM_MAU(MaNhomMau)
);
GO

CREATE TABLE QUY_DOI_DIEM (
  MaDoiQua VARCHAR(20) PRIMARY KEY,
  TenQua NVARCHAR(150),
  NgayDoi DATETIME DEFAULT GETDATE() ,
  DiemDoi INT,
  MaNguoiHien VARCHAR(20),
  FOREIGN KEY (MaNguoiHien) REFERENCES NGUOI_HIEN(MaNguoiHien)
);
GO

CREATE TABLE DANG_KY_CHIEN_DICH (
  MaChienDich VARCHAR(20),
  MaNguoiHien VARCHAR(20),
  NgayDangKy DATETIME,
  PRIMARY KEY (MaChienDich, MaNguoiHien),
  FOREIGN KEY (MaChienDich) REFERENCES CHIEN_DICH(MaChienDich),
  FOREIGN KEY (MaNguoiHien) REFERENCES NGUOI_HIEN(MaNguoiHien)
);
GO

CREATE TABLE VI_TRI_KHO (
  MaViTri VARCHAR(20) PRIMARY KEY,
  TenTu NVARCHAR(50),
  Ngan INT
);
GO

CREATE TABLE GOI_MAU_TOAN_PHAN (
  MaGoiMau VARCHAR(20) PRIMARY KEY,
  NgayHien DATETIME DEFAULT GETDATE(),
  TheTich INT CHECK (TheTich in (250,350,450)),
  TrangThaiKiemDinh NVARCHAR(20) DEFAULT N'Chờ xét nghiệm',
  MaNguoiHien VARCHAR(20),
  MaNhomMau VARCHAR(5),
  MaChienDich VARCHAR(20),
  MaNV_ThuNhan VARCHAR(20),
  FOREIGN KEY (MaNguoiHien) REFERENCES NGUOI_HIEN(MaNguoiHien),
  FOREIGN KEY (MaNhomMau) REFERENCES NHOM_MAU(MaNhomMau),
  FOREIGN KEY (MaChienDich) REFERENCES CHIEN_DICH(MaChienDich),
  FOREIGN KEY (MaNV_ThuNhan) REFERENCES NHAN_VIEN(MaNV)
);
GO

CREATE TABLE KET_QUA_XET_NGHIEM (
  MaXetNghiem VARCHAR(20) PRIMARY KEY,
  LoaiXetNghiem NVARCHAR(100),
  KetQua NVARCHAR(20) check (KetQua in ('Dương tính','Âm tính')),
  NgayXetNghiem DATETIME,
  MaGoiMau VARCHAR(20),
  MaNV_ThucHien VARCHAR(20),
  FOREIGN KEY (MaGoiMau) REFERENCES GOI_MAU_TOAN_PHAN(MaGoiMau),
  FOREIGN KEY (MaNV_ThucHien) REFERENCES NHAN_VIEN(MaNV)
);
GO

CREATE TABLE THANH_PHAN_MAU (
  MaThanhPhan VARCHAR(20) PRIMARY KEY,
  LoaiThanhPhan NVARCHAR(30),
  TheTichThucTe INT,
  HanSuDung DATE,
  TrangThai NVARCHAR(20) DEFAULT N'Sẵn sàng',
  MaGoiMau VARCHAR(20),
  MaViTri VARCHAR(20),
  FOREIGN KEY (MaGoiMau) REFERENCES GOI_MAU_TOAN_PHAN(MaGoiMau),
  FOREIGN KEY (MaViTri) REFERENCES VI_TRI_KHO(MaViTri)
);
GO

CREATE TABLE BENH_NHAN (
  MaBenhNhan VARCHAR(20) PRIMARY KEY,
  HoTen NVARCHAR(120) NOT NULL,
  NgaySinh DATE,
  BenhAn NVARCHAR(500),
  MaNhomMau VARCHAR(5),
  MaBV VARCHAR(20),
  FOREIGN KEY (MaNhomMau) REFERENCES NHOM_MAU(MaNhomMau),
  FOREIGN KEY (MaBV) REFERENCES BENH_VIEN(MaBV)
);
GO

CREATE TABLE PHIEU_YEU_CAU (
  MaPhieuYC VARCHAR(20) PRIMARY KEY,
  NgayYeuCau DATETIME DEFAULT GETDATE(),
  LoaiThanhPhanCan NVARCHAR(30),
  SoLuongML INT,
  TrangThaiDuyet NVARCHAR(20) DEFAULT N'Chờ duyệt',
  MaBV VARCHAR(20),
  MaBenhNhan VARCHAR(20),
  MaNhomMau VARCHAR(5),
  MaNV_Duyet VARCHAR(20),
  FOREIGN KEY (MaBV) REFERENCES BENH_VIEN(MaBV),
  FOREIGN KEY (MaBenhNhan) REFERENCES BENH_NHAN(MaBenhNhan),
  FOREIGN KEY (MaNhomMau) REFERENCES NHOM_MAU(MaNhomMau),
  FOREIGN KEY (MaNV_Duyet) REFERENCES NHAN_VIEN(MaNV)
);
GO

CREATE TABLE PHIEU_XUAT (
  MaPhieuXuat VARCHAR(20) PRIMARY KEY,
  NgayXuat DATETIME DEFAULT GETDATE(),
  TongTheTich INT,
  MaPhieuYC VARCHAR(20),
  MaNV_Xuat VARCHAR(20),
  FOREIGN KEY (MaPhieuYC) REFERENCES PHIEU_YEU_CAU(MaPhieuYC),
  FOREIGN KEY (MaNV_Xuat) REFERENCES NHAN_VIEN(MaNV)
);
GO

CREATE TABLE CHI_TIET_XUAT (
  MaPhieuXuat VARCHAR(20),
  MaThanhPhan VARCHAR(20),
  KetQuaPhanUngCheo NVARCHAR(20),
  PRIMARY KEY (MaPhieuXuat, MaThanhPhan),
  FOREIGN KEY (MaPhieuXuat) REFERENCES PHIEU_XUAT(MaPhieuXuat),
  FOREIGN KEY (MaThanhPhan) REFERENCES THANH_PHAN_MAU(MaThanhPhan)
);
GO

